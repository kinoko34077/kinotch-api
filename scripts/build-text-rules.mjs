import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import JSON5 from "json5";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rulesDirectory = path.join(projectRoot, "src", "text-core", "rules");
const outputPath = path.join(projectRoot, "src", "text-core", "rules.generated.mjs");

const manifest = JSON5.parse(
  await readFile(path.join(rulesDirectory, "transform-bundles.json5"), "utf8"),
);
const files = {};

for (const bundle of manifest.bundles ?? []) {
  const fileName = path.basename(bundle.path);
  files[bundle.id] = JSON5.parse(
    await readFile(path.join(rulesDirectory, fileName), "utf8"),
  );
}

const generated = [
  "// Generated by scripts/build-text-rules.mjs. Do not edit manually.",
  `export const RULE_MANIFEST = ${JSON.stringify(manifest)};`,
  `export const RULE_FILES = ${JSON.stringify(files)};`,
  "",
].join("\n");

await writeFile(outputPath, generated, "utf8");
console.log(`Generated ${path.relative(projectRoot, outputPath)}`);
