import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import path from "node:path";

const SNAPSHOT_FILES = [
  "vendor/kuromoji.js",
  "vendor/structured-dictionary.js",
  "vendor/transform-engine.js",
  "vendor/transform-shared.js",
  "rules.generated.mjs",
];

function updateHash(hash, relativePath, bytes) {
  hash.update(relativePath);
  hash.update("\0");
  hash.update(bytes);
  hash.update("\0");
}

async function hashFiles(projectRoot, relativePaths) {
  const hash = createHash("sha256");
  for (const relativePath of relativePaths) {
    const bytes = await readFile(path.join(projectRoot, "src", "text-core", relativePath));
    updateHash(hash, relativePath.replaceAll("\\", "/"), bytes);
  }
  return hash.digest("hex");
}

export async function generateTextMetadataSource(projectRoot) {
  const dictionaryRoot = path.join(projectRoot, "src", "text-core", "dict");
  const dictionaryNames = (await readdir(dictionaryRoot))
    .filter((name) => name.endsWith(".dat.gz"))
    .sort();
  const dictionaryHash = await hashFiles(
    projectRoot,
    dictionaryNames.map((name) => path.join("dict", name)),
  );
  const snapshotHash = await hashFiles(projectRoot, [
    ...SNAPSHOT_FILES,
    ...dictionaryNames.map((name) => path.join("dict", name)),
  ]);

  return [
    "// Generated by scripts/build-text-metadata.mjs. Do not edit manually.",
    "export const TEXT_CORE_METADATA_VERSION = \"snapshot-v1\";",
    "export const TEXT_CORE_RULE_SET_VERSION = \"rules-v1\";",
    "export const TEXT_CORE_DICTIONARY_VERSION = \"dictionary-v1\";",
    `export const TEXT_CORE_SNAPSHOT_HASH = ${JSON.stringify(snapshotHash)};`,
    `export const TEXT_CORE_DICTIONARY_HASH = ${JSON.stringify(dictionaryHash)};`,
    `export const TEXT_CORE_SOURCE_REVISION = ${JSON.stringify(process.env.TEXT_CORE_SOURCE_REVISION ?? "unknown")};`,
    "",
  ].join("\n");
}
