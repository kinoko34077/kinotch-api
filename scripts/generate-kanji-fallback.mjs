import { readFile } from "node:fs/promises";
import path from "node:path";

const GENERATED_HEADER = "// Generated by scripts/build-kanji-fallback.mjs. Do not edit manually.\n";

export function compareKanjiKeys(leftValue, rightValue) {
  const left = Array.isArray(leftValue) ? leftValue[0] : leftValue;
  const right = Array.isArray(rightValue) ? rightValue[0] : rightValue;
  return left < right ? -1 : left > right ? 1 : 0;
}

export async function generateKanjiFallbackSource(projectRoot) {
  const generatedPath = path.join(projectRoot, "src", "text-core", "rules.generated.mjs");
  const source = await readFile(generatedPath, "utf8");
  const match = source.match(/export const RULE_FILES = (.+);\n/);
  if (!match) throw new Error("Could not read generated text rule manifest");

  const ruleFiles = JSON.parse(match[1]);
  const legacyMap = ruleFiles["legacy-kanji"]?.character_map;
  const generalMap = ruleFiles["general-character-replacements"]?.character_map;
  if (!legacyMap || typeof legacyMap !== "object" || !generalMap || typeof generalMap !== "object") {
    throw new Error("Canonical kanji character maps are missing");
  }

  const pairs = Object.entries({ ...generalMap, ...legacyMap })
    .sort(compareKanjiKeys);
  return `${GENERATED_HEADER}export const KANJI_VARIANT_PAIRS = Object.freeze(${JSON.stringify(pairs)});\n`;
}
