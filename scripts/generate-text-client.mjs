import { readFile } from "node:fs/promises";
import path from "node:path";

const GENERATED_HEADER = "// Generated by scripts/build-text-client.mjs. Do not edit manually.\n";

export async function readCanonicalTextClientSource(projectRoot) {
  return readFile(path.join(projectRoot, "src", "client", "text-transform.js"), "utf8");
}

export async function generateTextClientSource(projectRoot) {
  const source = await readCanonicalTextClientSource(projectRoot);
  return `${GENERATED_HEADER}${source}`;
}
