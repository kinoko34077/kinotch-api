import path from "node:path";
import { readCanonicalTextClientSource } from "./generate-text-client.mjs";

const EXPORT_NAMES = [
  "DEFAULT_TEXT_API_BASE_URL",
  "DEFAULT_TEXT_API_TIMEOUT_MS",
  "TextTransformApiError",
  "createTextTransformClient",
];

export async function generateBrowserClientSource(projectRoot) {
  const source = await readCanonicalTextClientSource(projectRoot);
  const body = source
    .replace(/^export\s+class\s+/gm, "class ")
    .replace(/^export\s+const\s+/gm, "const ")
    .replace(/^export\s+function\s+/gm, "function ");

  if (/^export\b/m.test(body)) {
    throw new Error("Unsupported export syntax in the shared text transform client");
  }

  return [
    "// Generated by scripts/build-browser-client.mjs. Do not edit manually.",
    "(function (root) {",
    '  "use strict";',
    body,
    "  root.KinotchTextTransform = Object.freeze({",
    ...EXPORT_NAMES.map((name) => `    ${name},`),
    "  });",
    "})(typeof globalThis !== \"undefined\" ? globalThis : this);",
    "",
  ].join("\n");
}
